CREATE TABLE FACT_SALES (
  ROW_ID NUMBER(10) PRIMARY KEY,
  ORDER_ID VARCHAR2(30) NOT NULL,
  ORDER_DATE DATE NOT NULL,
  SHIP_DATE DATE,
  SHIP_MODE VARCHAR2(30),
  CUSTOMER_ID VARCHAR2(30),
  CUSTOMER_NAME VARCHAR2(100),
  SEGMENT VARCHAR2(30),
  COUNTRY VARCHAR2(60),
  CITY VARCHAR2(60),
  STATE_NAME VARCHAR2(60),
  POSTAL_CODE VARCHAR2(20),
  REGION VARCHAR2(30),
  PRODUCT_ID VARCHAR2(40),
  CATEGORY VARCHAR2(40),
  SUB_CATEGORY VARCHAR2(50),
  PRODUCT_NAME VARCHAR2(200),
  SALES NUMBER(14,2),
  QUANTITY NUMBER(10),
  DISCOUNT NUMBER(8,4),
  PROFIT NUMBER(14,2)
);

SELECT COUNT(*) AS ROW_COUNT,
       COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
       ROUND(SUM(SALES),2) AS TOTAL_SALES,
       ROUND(SUM(PROFIT),2) AS TOTAL_PROFIT
FROM FACT_SALES;

SELECT COUNT(*) AS NULL_ORDER_DATES
FROM FACT_SALES WHERE ORDER_DATE IS NULL;

SELECT ROW_ID, COUNT(*) AS DUP_COUNT
FROM FACT_SALES GROUP BY ROW_ID HAVING COUNT(*) > 1;

SELECT COUNT(*) AS NEGATIVE_SALES
FROM FACT_SALES WHERE SALES < 0;

SELECT ROUND(SUM(SALES),2) AS TOTAL_SALES,
       ROUND(SUM(PROFIT),2) AS TOTAL_PROFIT,
       COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
       SUM(QUANTITY) AS UNITS_SOLD,
       ROUND(SUM(SALES)/NULLIF(COUNT(DISTINCT ORDER_ID),0),2) AS AVG_ORDER_VALUE,
       ROUND(SUM(PROFIT)/NULLIF(SUM(SALES),0)*100,2) AS PROFIT_MARGIN
FROM FACT_SALES;

SELECT TO_CHAR(ORDER_DATE,'YYYY-MM') AS SALES_MONTH,
       ROUND(SUM(SALES),2) AS SALES,
       ROUND(SUM(PROFIT),2) AS PROFIT,
       COUNT(DISTINCT ORDER_ID) AS ORDERS
FROM FACT_SALES
GROUP BY TO_CHAR(ORDER_DATE,'YYYY-MM')
ORDER BY SALES_MONTH;

SELECT REGION, ROUND(SUM(SALES),2) AS SALES,
       ROUND(SUM(PROFIT),2) AS PROFIT
FROM FACT_SALES
GROUP BY REGION ORDER BY SALES DESC;

SELECT PRODUCT_NAME, CATEGORY, SALES, PROFIT, SALES_RANK
FROM (
  SELECT PRODUCT_NAME, CATEGORY, SUM(SALES) AS SALES,
         SUM(PROFIT) AS PROFIT,
         DENSE_RANK() OVER (ORDER BY SUM(SALES) DESC) AS SALES_RANK
  FROM FACT_SALES
  GROUP BY PRODUCT_NAME, CATEGORY
)
WHERE SALES_RANK <= 10
ORDER BY SALES_RANK;

CREATE OR REPLACE VIEW VW_MONTHLY_SALES AS
SELECT TRUNC(ORDER_DATE,'MM') AS MONTH_START,
       SUM(SALES) AS TOTAL_SALES,
       SUM(PROFIT) AS TOTAL_PROFIT,
       COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM FACT_SALES
GROUP BY TRUNC(ORDER_DATE,'MM');